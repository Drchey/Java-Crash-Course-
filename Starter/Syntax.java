package Starter;

/*
Every line of code that runs in Java must be inside a class. 
The class name should always start with an uppercase first letter.
In our example, we named the class "Syntax".


When saving the file, save it using the class name and add .java to the end of the filename
 */
public class Syntax {

    /*
     * The main() method is required in every Java program. It is where the program
     * starts running:
     */
    public static void main(String[] args) {

        /*
         * In Java, it is important that you end every statement with a semicolon ;.
         * The statements are executed, one by one, in the same order as they are
         * written:
         */

        // Comments can be written with 2 slashes (//) or (/* */) for multi line
        // comments
        System.out.println("Hello World");
    }

}
